def style_header(cell, fill_color=NAVY):
    cell.font = Font(name="Calibri", bold=True, color=WHITE, size=12)
    cell.fill = PatternFill("solid", fgColor=fill_color)
    cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="left")


def style_stage(cell):
    cell.font = Font(name="Calibri", bold=True, size=11, color=NAVY)
    cell.fill = PatternFill("solid", fgColor=SOFT)
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    cell.border = thin


def style_body(cell, highlight=False):
    cell.font = Font(name="Calibri", size=11)
    cell.fill = PatternFill("solid", fgColor=YELLOW if highlight else WHITE)
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    cell.border = thin


def style_note(cell):
    cell.font = Font(name="Calibri", italic=True, size=10, color="555555")
    cell.fill = PatternFill("solid", fgColor=LIGHT)
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    cell.border = thin


def set_widths(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def estimate_row_height(values, col_widths, min_h=28, line_h=16, padding=12):
    max_lines = 1
    for val, width in zip(values, col_widths):
        if not val:
            continue
        text = str(val)
        parts = text.split("\n")
        lines = 0
        chars_per_line = max(int(width * 0.85), 10)
        for part in parts:
            lines += max(1, (len(part) + chars_per_line - 1) // chars_per_line)
        max_lines = max(max_lines, lines)
    return max(min_h, int(max_lines * line_h + padding))


def add_row(ws, r, values, kinds=None, col_widths=None):
    kinds = kinds or ["body"] * len(values)
    for c, (val, kind) in enumerate(zip(values, kinds), 1):
        cell = ws.cell(r, c, val)
        if kind == "stage":
            style_stage(cell)
        elif kind == "note":
            style_note(cell)
        elif kind == "highlight":
            style_body(cell, highlight=True)
        elif kind == "header":
            style_header(cell)
        else:
            style_body(cell)
    if col_widths:
        ws.row_dimensions[r].height = estimate_row_height(values, col_widths)
    return r + 1


