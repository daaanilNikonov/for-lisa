# Таймеры из файла «Игра клуб продавцов.docx»:
# 10/30/50 → 1–1,5 мин; 70/100 → 2 мин; 150 → 3 мин
def think_seconds(points: int) -> int:
    if points <= 50:
        return 90
    if points <= 100:
        return 120
    return 180


def timer_label(points: int) -> str:
    sec = think_seconds(points)
    if sec % 60 == 0:
        return f"{sec // 60} мин"
    return f"{sec // 60}:{sec % 60:02d}"


