            p2 = tf.add_paragraph()
            p2.space_before = Pt(8)
            set_run(p2.add_run(), "Отработка возражений", 30, True, BLUE)
            p3 = tf.add_paragraph()
            p3.space_before = Pt(14)
            set_run(p3.add_run(), "Формат «100 к 1»  ·  командная Своя игра", 15, True, WHITE)
