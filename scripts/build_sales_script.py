def add_obj_header(ws, row, service):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=3)
    ws.cell(row, 1, service)
    style_range(ws, row, 1, 3, HEADER_BG, font(12, True, WHITE), align(h="left"))
    set_row_height(ws, row, 22)


def add_obj_cols(ws, row):
    for i, h in enumerate(["Возражение", "Отработка для менеджера", "На кого сильнее давит"], 1):
        cell = ws.cell(row, i, h)
        cell.font = font(10, True, WHITE)
        cell.fill = fill(BLUE)
        cell.alignment = align(h="center")
        cell.border = BORDER
    set_row_height(ws, row, 20)


def add_obj(ws, row, objection, answer, lpr, bg=SOFT):
    ws.cell(row, 1, objection)
    ws.cell(row, 2, answer)
    ws.cell(row, 3, lpr)
    style_range(ws, row, 1, 3, bg, font(10), align(v="top"))
    ws.cell(row, 1).font = font(10, True, DARK)
    ws.cell(row, 3).alignment = align(h="center", v="center")
    # estimate height
    lines = max(2, len(answer) // 70 + answer.count("\n") + 1)
    set_row_height(ws, row, min(18 + lines * 12, 110))


