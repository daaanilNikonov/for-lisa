def font(size=11, bold=False, color=DARK, italic=False):
    return Font(name=FONT, size=size, bold=bold, color=color, italic=italic)


def fill(hex_color: str) -> PatternFill:
    return PatternFill("solid", fgColor=hex_color)


def align(wrap=True, h="left", v="center"):
    return Alignment(wrap_text=wrap, horizontal=h, vertical=v)


def style_range(ws, row, start_col, end_col, fill_color=None, f=None, a=None):
    for c in range(start_col, end_col + 1):
        cell = ws.cell(row, c)
        cell.border = BORDER
        if fill_color:
            cell.fill = fill(fill_color)
        if f:
            cell.font = f
        if a:
            cell.alignment = a


def set_row_height(ws, row, height):
    ws.row_dimensions[row].height = height


def write_header_block(ws, title: str, subtitle: str, cols: int = 5):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=cols)
    ws["A1"] = title
    style_range(ws, 1, 1, cols, HEADER_BG, font(16, True, WHITE), align(h="center"))
    set_row_height(ws, 1, 28)

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=cols)
    ws["A2"] = subtitle
    style_range(ws, 2, 1, cols, BLUE, font(10, False, WHITE), align(h="center"))
    set_row_height(ws, 2, 22)


def write_lpr_headers(ws, row: int):
    headers = ["ЭТАП", "РУКОВОДИТЕЛЬ", "БУХГАЛТЕР", "КАДРОВИК", "IT-СПЕЦИАЛИСТ"]
    for i, h in enumerate(headers, 1):
        cell = ws.cell(row, i, h)
        cell.font = font(11, True, WHITE)
        cell.fill = fill(BLUE)
        cell.alignment = align(h="center")
        cell.border = BORDER
    set_row_height(ws, row, 22)


def add_stage_row(ws, row: int, stage: str, texts: list[str], height: int = 72, bg: str = SOFT):
    ws.cell(row, 1, stage)
    for i, text in enumerate(texts, 2):
        ws.cell(row, i, text)
    style_range(ws, row, 1, 5, bg, font(10), align(v="top"))
    ws.cell(row, 1).font = font(10, True, DARK)
    ws.cell(row, 1).alignment = align(h="center", v="center")
    set_row_height(ws, row, height)


def add_section_banner(ws, row: int, text: str, color: str = "1E3A4C"):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=5)
    ws.cell(row, 1, text)
    style_range(ws, row, 1, 5, color, font(11, True, WHITE), align(h="left"))
    set_row_height(ws, row, 22)


