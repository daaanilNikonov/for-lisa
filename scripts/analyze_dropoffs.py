def classify(stage: str) -> str | None:
    s = stage.lower().replace("\n", " ").strip()

    if s.startswith("оценка готовности") and "отказ" not in s and "после демо отказ" not in s:
        return None
    if s == "уточнение информации о клиенте и потребности":
        return None
    if s in (
        "лид сконвертирован",
        "лид сконвертирован (кп)",
        "лид сконвертирован (кп, подключение)",
        "лид сконвертирован (жду ответа)",
        "лид сконвертирован (кп, демо, подключение после введения нужного функционала)",
    ):
        return None

    if "потом позвонить" in s or "связаться в ноябре" in s:
        return "Отложили решение / перенести контакт"

    if "неверный номер" in s or "номер не обслуживается" in s:
        return "Некорректный или мёртвый номер"

    if (
        "не удалось дозвон" in s
        or "недозвон" in s
        or "закрыты, недозвон" in s
        or "не удалось связаться с лпр" in s
        or "передали контакт лпр, дальше недозвон" in s
    ):
        return "Недозвон / нет контакта с ЛПР"

    if (
        "скинул" in s
        or "бросили трубку" in s
        or "не захотела разговаривать" in s
        or "заблокировали" in s
        or "не сотрудничаю" in s
        or "после того как представился" in s
        or "помолчала" in s
        or "было удобно говорить потом стало неудобно" in s
    ):
        return "Сбросили трубку / отказ от разговора"

    if "не наша ца" in s or "магазин парфюмерии" in s or "мед. клиника" in s:
        return "Не целевая аудитория"

    if (
        "закрывают" in s
        or "сейчас не работает" in s
        or "ничем не занимается" in s
        or "филиал удален" in s
    ):
        return "Бизнес закрыт или не работает"

    if (
        "не подходит онлайн" in s
        or "не хочет онлайн" in s
        or "не интересует онлайн" in s
        or "не нравится формат онлайн" in s
        or "очный формат" in s
        or "записью по звонкам" in s
        or "через тг запись" in s
        or "есть онлайн запись" in s
        or "нужна доп информация о клиенте" in s
        or "записывают клиентов только после диалога" in s
    ):
        return "Не подходит формат онлайн-записи"

    if any(
        x in s
        for x in (
            "дикиди",
            "мастерс",
            "yclients",
            "юк",
            "юклаенс",
            "арник",
            "своя разработка",
            "другим сервисом",
            "пользуются",
        )
    ):
        return "Устраивает текущий сервис конкурента"

    if (
        "не заинтересовало после кп" in s
        or "после демо отказ" in s
        or "не заинтересовало наше предложение" in s
    ):
        return "Отказ после КП или демо"

    if any(
        x in s
        for x in (
            "неинтерес",
            "неактуаль",
            "ничего не хотят",
            "не интересует",
            "отказ в тг",
            "их не интересует",
            "закрываются, ничего",
        )
    ):
        return "Неинтересно / отказ без конкретной причины"

    if s == "другое":
        return "Причина не зафиксирована"

    return "Прочие причины"


def main() -> None:
    wb = openpyxl.load_workbook(SRC, data_only=True)
    ws = wb.active
    rows = list(ws.iter_rows(min_row=2, values_only=True))

    counts: Counter[str] = Counter()
    examples: dict[str, list[str]] = defaultdict(list)
    active = 0

    for r in rows:
        stage = str(r[1] or "")
        cat = classify(stage)
        if cat is None:
            active += 1
            continue
        counts[cat] += 1
        if len(examples[cat]) < 3:
            examples[cat].append(stage.replace("\n", " ")[:140])

    total_drop = sum(counts.values())
    payload = {
        "source": SRC.name,
        "total_leads": len(rows),
        "active_or_success": active,
        "drop_offs": total_drop,
        "reasons": [
            {
                "reason": cat,
                "count": c,
                "share": round(100 * c / total_drop, 1) if total_drop else 0,
                "comment": THESES.get(cat, ""),
                "examples": examples[cat],
            }
            for cat, c in counts.most_common()
        ],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Saved {OUT}")
    print(f"leads={payload['total_leads']} drops={payload['drop_offs']} active={active}")
    for r in payload["reasons"]:
        print(f"  {r['count']:3d} ({r['share']:5.1f}%) {r['reason']}")


if __name__ == "__main__":
    main()
