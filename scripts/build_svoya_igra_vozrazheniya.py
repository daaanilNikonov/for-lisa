def sort_topic_questions():
    for topic in TOPICS:
        topic["questions"].sort(key=lambda q: POINTS.index(q["points"]))



def verify_package(path: Path) -> None:
    import zipfile

    def slide_key(name: str) -> int:
        return int(re.search(r"slide(\d+)", name).group(1))

    with zipfile.ZipFile(path) as z:
        slides = sorted(
            (n for n in z.namelist() if re.match(r"ppt/slides/slide\d+\.xml$", n)),
            key=slide_key,
        )
        board = z.read(slides[1]).decode("utf-8")
        h = board.count("hlinkClick")
        assert h >= 20, h
        delays = set()
        for s in slides[2:]:
            xml = z.read(s).decode("utf-8")
            assert "<p:timing" in xml, s
            delays |= {
                int(x)
                for x in re.findall(r'<p:cond delay="(\d+)"/>', xml)
                if x != "0"
            }
        assert delays and delays <= {90000, 120000, 180000}, delays
        media = [n for n in z.namelist() if n.startswith("ppt/media/") and n.endswith(".gif")]
        assert len(media) >= 3, media
        print(
            "Verify OK: board hlinks=",
            h,
            "delays=",
            sorted(delays),
            "timer gifs=",
            len(media),
        )


def main():
    if not TEMPLATE.exists():
        raise SystemExit(f"Template not found: {TEMPLATE}")
    for sec in (90, 120, 180):
        gif = TIMER_DIR / f"timer_{sec}s.gif"
        if not gif.exists():
            raise SystemExit(f"Timer GIF not found: {gif}")

    sort_topic_questions()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_COPY.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(TEMPLATE, OUT)

    prs = Presentation(str(OUT))
    delete_all_slides(prs)

    build_title(prs)
    board_slide, cell_shapes = build_board(prs)

    for ti, topic in enumerate(TOPICS):
        for qi, qdata in enumerate(topic["questions"]):
            q_slide = build_case_slide(prs, topic, qdata, board_slide)
            cell = cell_shapes.get((ti, qi))
            if cell is not None:
                link_to_slide(cell, q_slide)
                bind_text_run_hyperlink(cell)
                try:
                    cell.name = f"Cell_{ti}_{qi}"
                except Exception:
                    pass

    patch_theme_followed_hyperlink_red(prs)
    prs.save(str(OUT))
    shutil.copy2(OUT, OUT_COPY)

    n_q = sum(len(t["questions"]) for t in TOPICS)
    print(f"Saved: {OUT}")
    print(f"Copy:  {OUT_COPY}")
    print(f"Slides: {len(prs.slides)} (title + board + {n_q} cases)")
    print("Timers: 90s (30), 120s (70–100), 180s (150)")
    print('Themes:', ' | '.join(t['name'] for t in TOPICS))
    verify_package(OUT)


if __name__ == "__main__":
    main()
